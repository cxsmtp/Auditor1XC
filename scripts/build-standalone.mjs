#!/usr/bin/env node
/**
 * Builds cx-auditor.mjs: ONE self-contained file (library + GUI server + web page)
 * that you can copy anywhere and run with `node cx-auditor.mjs`.
 *
 *   node scripts/build-standalone.mjs          write cx-auditor.mjs
 *   node scripts/build-standalone.mjs --check  exit 1 if cx-auditor.mjs is out of date
 *
 * Sources of truth: cx_auditor.mjs, cx_auditor_gui.mjs, gui/*. Never edit the output by hand.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "cx-auditor.mjs");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8").replace(/\r\n/g, "\n");

const IMPORT_RE = /^import\s+(.+?)\s+from\s+"([^"]+)";\s*$/gm;

export function build() {
  const lib = read("cx_auditor.mjs");
  const gui = read("cx_auditor_gui.mjs");

  // Merge node:* imports from both files; drop the gui's import of the library.
  const defaults = new Map(), named = new Map();
  for (const src of [lib, gui]) {
    for (const [, spec, mod] of src.matchAll(IMPORT_RE)) {
      if (!mod.startsWith("node:")) continue;
      const m = spec.match(/^(\w+)?\s*,?\s*(?:\{([^}]*)\})?$/);
      if (!m) throw new Error(`unsupported import form: import ${spec} from "${mod}"`);
      if (m[1]) {
        if (defaults.has(mod) && defaults.get(mod) !== m[1]) throw new Error(`conflicting default import for ${mod}`);
        defaults.set(mod, m[1]);
      }
      if (m[2]) for (const n of m[2].split(",").map((x) => x.trim()).filter(Boolean)) (named.get(mod) || named.set(mod, new Set()).get(mod)).add(n);
    }
  }
  const mods = [...new Set([...defaults.keys(), ...named.keys()])].sort();
  const imports = mods.map((mod) => {
    const parts = [];
    if (defaults.has(mod)) parts.push(defaults.get(mod));
    if (named.has(mod)) parts.push(`{ ${[...named.get(mod)].sort().join(", ")} }`);
    return `import ${parts.join(", ")} from "${mod}";`;
  }).join("\n");

  const strip = (src) => src.replace(/^#!.*\n/, "").replace(IMPORT_RE, "");
  const libBody = strip(lib).replace(/\/\/ @@CLI_MAIN_START[\s\S]*?\/\/ @@CLI_MAIN_END\n?/, "");
  if (libBody.includes("@@CLI_MAIN")) throw new Error("could not remove the CLI entry block");

  const assets = {};
  for (const f of fs.readdirSync(path.join(ROOT, "gui")).sort()) assets[f] = read(path.join("gui", f));
  const marker = "const EMBEDDED_ASSETS = null;";
  if (!gui.includes(marker)) throw new Error("EMBEDDED_ASSETS marker not found in cx_auditor_gui.mjs");
  // replacer *function*: the assets contain "$&" etc., which a replacement string would expand
  const guiBody = strip(gui).replace(marker, () => `const EMBEDDED_ASSETS = ${JSON.stringify(assets)};`);

  return `#!/usr/bin/env node
// =============================================================================
// cx-auditor.mjs - Checkmarx One Auditor, single-file edition (GUI).
//
//   node cx-auditor.mjs                 opens the GUI in your browser
//   node cx-auditor.mjs --port 9000     choose the port
//   node cx-auditor.mjs --no-open       don't open a browser, just print the URL
//
// Requires Node.js 18+. Nothing to install. This file is GENERATED by
// scripts/build-standalone.mjs from cx_auditor.mjs, cx_auditor_gui.mjs and gui/ -
// edit those, then rebuild.
// =============================================================================
${imports}

// ---------------------------------------------------------------- library (cx_auditor.mjs)
${libBody.trim()}

// ---------------------------------------------------------------- GUI server (cx_auditor_gui.mjs)
${guiBody.trim()}
`;
}

const out = build();
if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== out) {
    console.error("cx-auditor.mjs is out of date - run: node scripts/build-standalone.mjs");
    process.exit(1);
  }
  console.log("cx-auditor.mjs is up to date");
} else {
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${(out.length / 1024).toFixed(0)} KB)`);
}
